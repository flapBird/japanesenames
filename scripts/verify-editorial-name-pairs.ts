import { readFile, writeFile } from "node:fs/promises";
import { firstNames } from "../src/data/first-names";
import type { ImportedCandidate } from "./import-jmnedict";

const candidates = JSON.parse(await readFile("src/data/generated/candidates/jmnedict-candidates.json", "utf8")) as ImportedCandidate[];
const pairs: Record<string, string[]> = {};
for (const name of firstNames) {
  for (const variation of name.variations) {
    pairs[`${variation.kanji}:${name.hiragana}`] = [...new Set(candidates
      .filter((item) => item.kind !== "surname" && item.kanji === variation.kanji && item.hiragana === name.hiragana)
      .map((item) => item.upstreamEntryId))].sort();
  }
}
await writeFile("src/data/editorial-pair-evidence.ts", `// Exact spelling/reading matches in the local JMnedict 2026-08-01 snapshot.\n// Generated by scripts/verify-editorial-name-pairs.ts. Empty arrays mean no match\n// in this snapshot, not proof that a spelling is invalid. No usage inference.\nexport const editorialPairEvidence: Record<string, string[]> = ${JSON.stringify(pairs, null, 2)};\n`);
console.log(`${Object.values(pairs).filter((ids) => ids.length).length}/${Object.keys(pairs).length} editorial pairs matched.`);
